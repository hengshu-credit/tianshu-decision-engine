const { test, expect } = require('@playwright/test')
const { installDistRoutes } = require('./support/distRoutes.cjs')
const { createDetailApiData } = require('./support/detailFixtures.cjs')
const { createOperationsApiData } = require('./support/operationsFixtures.cjs')
const origin = process.env.E2E_DEV_BASE_URL || 'http://tianshu.local'
const prepare = (page, apiData) => installDistRoutes(page, { origin, liveStatic: Boolean(process.env.E2E_DEV_BASE_URL), apiData })

test('同一管理页完成事件类型和事件的新增、修改、删除，取消关闭保留类型输入', async ({ page }, testInfo) => {
  let types = [], events = []
  const data = new Map([
    ['/api/rule/ledger/types', () => types],
    ['/api/rule/ledger/events/manage', () => ({ records: events, total: events.length })],
    ['POST /api/rule/ledger/types', ({ request }) => { const input = request.postDataJSON(); types = [{ ...input, id: '101', value: '101', label: input.name, version: 0, canManage: true }]; return types[0] }],
    ['PUT /api/rule/ledger/types/101', ({ request }) => { const input = request.postDataJSON(); expect(input.version).toBe(0); types = [{ ...types[0], ...input, label: input.name, version: 1 }]; return types[0] }],
    ['POST /api/rule/ledger/events', ({ request }) => { const input = request.postDataJSON(); expect(String(input.typeId)).toBe('101'); events = [{ ...input, id: '201', version: 0, typeName: types[0].name, canEdit: true }]; return events[0] }],
    ['PUT /api/rule/ledger/events/201', ({ request }) => { events = [{ ...events[0], ...request.postDataJSON(), version: 1 }]; return events[0] }],
    ['DELETE /api/rule/ledger/events/201', ({ url }) => { expect(url.searchParams.get('version')).toBe('1'); events = []; return null }],
    ['DELETE /api/rule/ledger/types/101', ({ url }) => { expect(url.searchParams.get('version')).toBe('1'); types = []; return null }],
  ])
  const harness = await prepare(page, data)
  await page.goto(`${origin}/#/ledger?tab=management`)
  const typesRegion = page.getByRole('region', { name: '事件类型管理', exact: true })
  const eventsRegion = page.getByRole('region', { name: '事件管理', exact: true })
  await typesRegion.getByRole('button', { name: '新增事件类型', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '新增事件类型', exact: true })
  await dialog.getByRole('textbox', { name: '类型编码' }).fill('TYPE_KEEP_Code')
  await dialog.getByRole('textbox', { name: '类型名称' }).fill('专项验收类型')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('dialog', { name: '未保存提醒' }).getByRole('button', { name: '继续编辑' }).click()
  await expect(dialog.getByRole('textbox', { name: '类型名称' })).toHaveValue('专项验收类型')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(typesRegion.getByRole('cell', { name: '专项验收类型', exact: true })).toBeVisible()
  await typesRegion.getByRole('button', { name: '编辑', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '编辑事件类型', exact: true })
  await dialog.getByRole('textbox', { name: '类型名称' }).fill('已更新类型')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(typesRegion.getByRole('cell', { name: '已更新类型', exact: true })).toBeVisible()
  await eventsRegion.getByRole('button', { name: '新建事件', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '新建事件', exact: true })
  await expect.poll(() => dialog.evaluate(element => element.querySelector('form').getBoundingClientRect().top - element.querySelector('.el-dialog__header').getBoundingClientRect().bottom)).toBeGreaterThanOrEqual(15)
  await dialog.getByRole('textbox', { name: '事件编码', exact: true }).fill('EVENT_KEEP_Code')
  await dialog.getByRole('textbox', { name: '事件名称', exact: true }).fill('专项验收事件')
  await dialog.getByRole('textbox', { name: '状态值 1', exact: true }).fill('待处理')
  await dialog.locator('.el-form-item').filter({ hasText: '当前状态' }).locator('.el-select').click()
  await page.getByRole('option', { name: '待处理', exact: true }).click()
  await dialog.locator('.el-form-item').filter({ hasText: '事件类型' }).locator('.el-select').click()
  await page.getByRole('option', { name: '已更新类型', exact: true }).click()
  await dialog.locator('.el-form-item').filter({ hasText: '作用范围' }).locator('.el-select').click()
  await page.getByRole('option', { name: /全局/ }).click()
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(eventsRegion.getByRole('cell', { name: '专项验收事件', exact: true })).toBeVisible()
  await eventsRegion.getByRole('button', { name: '编辑', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '编辑事件', exact: true })
  await dialog.getByRole('textbox', { name: '事件名称', exact: true }).fill('已更新事件')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(eventsRegion.getByRole('cell', { name: '已更新事件', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('ledger-management.png'), fullPage: true })
  await eventsRegion.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('dialog', { name: '确认删除', exact: true }).getByRole('button', { name: '确定', exact: true }).click()
  await expect(eventsRegion.getByRole('cell', { name: '已更新事件', exact: true })).toHaveCount(0)
  await typesRegion.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('dialog', { name: '确认删除', exact: true }).getByRole('button', { name: '确定', exact: true }).click()
  await expect(typesRegion.getByRole('cell', { name: '已更新类型', exact: true })).toHaveCount(0)
  harness.assertClean()
})

test('发布概览集中展示选中修订、线上版本、依赖变更和过期回归证据', async ({ page }) => {
  const data = createDetailApiData()
  const revisions = [{ id: 42, definitionId: 101, revisionNo: 8, state: 'DRAFT', lockVersion: 2, modelJson: '{}' }, { id: 41, definitionId: 101, revisionNo: 7, state: 'PUBLISHED', lockVersion: 3 }]
  data.set('/api/rule/definition/101/revisions', revisions)
  data.set('POST /api/rule/definition/101/revisions/42/preflight', { revisionId: 42, lockVersion: 2, valid: false, warnings: [{ code: 'DEPENDENCY_CHANGED', message: '名单依赖已有新版本' }], errors: [], regression: { allowed: false, requiredCount: 1, passedCount: 0, staleCount: 1, failedCount: 0, missingCount: 0, message: '依赖变化，证据已过期' } })
  data.set('/api/rule/definition/101/api-scenarios/reports', { records: [], total: 0 })
  const harness = await prepare(page, data)
  await page.goto(`${origin}/#/rule/101`)
  const panel = page.getByRole('region', { name: '发布就绪概览' })
  await expect(panel).toContainText('v8')
  await expect(panel).toContainText('修订 v7')
  await page.getByRole('button', { name: '发布前校验', exact: true }).click()
  await expect(panel).toContainText('名单依赖已有新版本')
  await expect(panel).toContainText('依赖变化，证据已过期')
  await panel.getByRole('button', { name: '查看回归证据', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '回归报告', exact: true })).toBeVisible()
  harness.assertClean()
})

test('版本来源与真实联调模式分开展示，清单指出外数和名单写入', async ({ page }) => {
  const data = createOperationsApiData()
  const schema = data.get('POST /api/rule/test-schema')
  data.set('POST /api/rule/test-schema', async context => ({ ...await schema(context), runtimeNodes: [{ refId: '7', sourceType: 'API', label: '征信取值' }, { refId: '8', sourceType: 'SFTP', label: '远端文件' }] }))
  data.set('/api/rule/definition/101/revisions/41', { ...data.get('/api/rule/definition/101/revisions/41'), modelJson: JSON.stringify({ actionData: [{ type: 'api-call', apiId: '91' }, { type: 'list-write', listIds: ['2'], operation: 'ADD_ONLY' }] }) })
  const harness = await prepare(page, data)
  await page.goto(`${origin}/#/test`)
  await page.locator('.test-left .el-form-item').filter({ hasText: '规则' }).locator('.el-select').click()
  await page.getByRole('option', { name: /age_rule/ }).click()
  await page.getByTestId('rule-test-source').click()
  await page.getByRole('option', { name: /草稿\s*1/ }).click()
  const panel = page.getByRole('region', { name: '执行模式与影响清单' })
  await expect(panel).toContainText('执行模式：真实联调')
  await expect(panel).toContainText('征信取值')
  await expect(panel).toContainText('远端文件')
  await expect(panel).toContainText('名单 #2 · 仅新增')
  await expect(panel).toContainText('可能计费')
  harness.assertClean()
})

test('失败日志保留快照依据、外部调用和名单交接状态，并连接到对应配置', async ({ page }) => {
  const data = new Map([...createOperationsApiData(), ...createDetailApiData()])
  const row = data.get('/api/rule/log/list').records[0]
  row.success = 0; row.rootRuleId = 101; row.projectId = 1
  row.traceInfo = JSON.stringify([{ traceKind: 'RULE', schemaVersion: 2, ruleId: 101, modelJson: '{}', events: [{ type: 'MODULE_CALL', moduleType: 'API', resourceId: 22, status: 'FAILED', errorMessage: '供应商超时' }, { type: 'LIST_ACTION', result: { status: 'QUEUED', taskId: 'task-keep' } }] }])
  const harness = await prepare(page, data)
  await page.goto(`${origin}/#/log`)
  await page.getByRole('row').filter({ hasText: row.traceId }).getByRole('button', { name: '详情', exact: true }).click()
  const panel = page.getByRole('region', { name: '执行排障指引' })
  await expect(panel).toContainText('供应商超时')
  await expect(panel).toContainText('已保留执行时设计快照')
  await expect(panel).toContainText('尚不能证明已完成写入')
  await expect(panel).toContainText('不要重新触发整条规则')
  await panel.getByRole('button', { name: '查看对应配置', exact: true }).first().click()
  await expect(page).toHaveURL(/#\/datasource\/api\/22$/)
  harness.assertClean()
})
