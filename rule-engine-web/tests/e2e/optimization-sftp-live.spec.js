const { test, expect } = require('@playwright/test')
const fs = require('node:fs')
const base = process.env.E2E_BASE_URL
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })

test('真实 SFTP 协议：指纹校验、凭据审批清除与恢复', async ({ page }, testInfo) => {
  test.skip(!base || !process.env.E2E_ISOLATED_OPTIMIZATION || !process.env.E2E_SFTP_CONFIG_FILE, '需要本机只读 SFTP 协议夹具')
  test.setTimeout(180000)
  const config = JSON.parse(fs.readFileSync(process.env.E2E_SFTP_CONFIG_FILE, 'utf8'))
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const name = `SFTP验收${Date.now()}`
  await page.goto(`${base}/#/sftp`)
  await page.locator('input[autocomplete="username"]').fill(process.env.E2E_USERNAME)
  await page.locator('input[autocomplete="current-password"]').fill(process.env.E2E_PASSWORD)
  await page.locator('button[type="submit"]').click()
  await page.getByRole('button', { name: '新建 SFTP 数据源', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: /SFTP 数据源/ })
  await dialog.locator('.el-form-item').filter({ hasText: '作用范围' }).locator('.el-select').click()
  await page.getByRole('option', { name: /全局/ }).click()
  await dialog.getByRole('textbox', { name: /数据源编码$/ }).fill(`SFTP_${Date.now()}`)
  await dialog.getByRole('textbox', { name: /数据源名称$/ }).fill(name)
  await dialog.getByRole('textbox', { name: /主机$/ }).fill('127.0.0.1')
  await dialog.getByRole('spinbutton', { name: '端口', exact: true }).fill(String(config.port))
  await dialog.getByRole('textbox', { name: /用户名$/ }).fill(config.username)
  await dialog.getByRole('textbox', { name: '密码', exact: true }).fill(config.password)
  const strict = dialog.locator('.el-form-item').filter({ hasText: '主机指纹校验' }).getByRole('switch')
  if (await strict.getAttribute('aria-checked') !== 'true') await dialog.locator('.el-form-item').filter({ hasText: '主机指纹校验' }).locator('.el-switch').click()
  await dialog.getByRole('textbox', { name: 'known_hosts', exact: true }).fill(config.knownHosts)
  await dialog.getByRole('button', { name: '测试连接', exact: true }).click()
  await expect(dialog.getByText('SFTP 连接测试成功，结果对应本次测试配置', { exact: true })).toBeVisible({ timeout: 20000 })
  await dialog.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(dialog).toBeHidden()
  const row = () => page.getByRole('row').filter({ hasText: name })
  const publish = async () => {
    await row().getByRole('button', { name: '发布', exact: true }).click()
    await page.getByRole('dialog', { name: '提交发布审批', exact: true }).getByRole('button', { name: '确定', exact: true }).click()
    await expect(page.getByText('已提交发布审批，生产内容在审批通过前保持原状', { exact: true })).toBeVisible()
    await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '审批管理', exact: true }).click()
    await page.getByRole('row').filter({ hasText: name }).first().getByRole('button', { name: '查看', exact: true }).click()
    await expect(page).toHaveURL(/#\/approval\/\d+/)
    await page.getByRole('button', { name: '通过并生效', exact: true }).click()
    await page.getByRole('dialog', { name: '通过并立即生效', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
    await expect(page.locator('.header-meta')).toContainText('已通过', { timeout: 30000 })
    await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: 'SFTP管理', exact: true }).click()
  }
  await publish()
  await row().getByRole('button', { name: '编辑', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: '密码', exact: true })).toHaveValue('')
  await expect(dialog.getByRole('textbox', { name: 'known_hosts', exact: true })).toHaveValue('')
  await dialog.getByRole('button', { name: '测试连接', exact: true }).click()
  await expect(dialog.getByText('SFTP 连接测试成功，结果对应本次测试配置', { exact: true })).toBeVisible({ timeout: 20000 })
  await dialog.getByText('清除已存密码', { exact: true }).click()
  await expect(dialog.getByText('连接配置已变更，请重新测试', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(dialog).toBeHidden(); await publish()
  await row().getByRole('button', { name: '编辑', exact: true }).click()
  await expect(dialog.getByText('清除已存密码', { exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '测试连接', exact: true }).click()
  await expect(dialog.locator('.el-alert--error')).toBeVisible({ timeout: 20000 })
  await dialog.getByRole('textbox', { name: '密码', exact: true }).fill(config.password)
  await dialog.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(dialog).toBeHidden(); await publish()
  await row().getByRole('button', { name: '测试', exact: true }).click()
  await expect(page.getByText('SFTP 连接成功', { exact: true })).toBeVisible({ timeout: 20000 })
  await page.screenshot({ path: testInfo.outputPath('sftp-cleared-restored.png'), fullPage: true })
  expect(errors).toEqual([])
})
