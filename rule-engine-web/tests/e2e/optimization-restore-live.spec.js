const { test, expect } = require('@playwright/test')
const fs = require('node:fs')
const ui = require('./support/optimizationLive.cjs')
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })

test('恢复后名单和决策制品仍可通过 UI 查看、导出和下载', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_BASE_URL || !process.env.E2E_ISOLATED_OPTIMIZATION || !process.env.E2E_RUNTIME_ENV_FILE, '仅用于本机恢复验收')
  test.setTimeout(90000)
  const config = JSON.parse(fs.readFileSync(process.env.E2E_RUNTIME_ENV_FILE, 'utf8'))
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await ui.login(page, '/list')
  await page.getByRole('row').filter({ hasText: '名单验收' }).first().getByRole('button', { name: '详情', exact: true }).click()
  for (const tab of ['名单内容', '变更日志']) {
    await page.getByRole('tab', { name: tab, exact: true }).click()
    const toolbar = page.getByTestId(tab === '名单内容' ? 'record-filter-toolbar' : 'log-filter-toolbar')
    await expect(toolbar.getByRole('button', { name: '导入并审批', exact: true })).toBeVisible()
    const exported = page.waitForEvent('download')
    await toolbar.getByRole('button', { name: '导出', exact: true }).click()
    expect(await (await exported).failure()).toBeNull()
  }
  await page.setViewportSize({ width: 560, height: 900 })
  await expect(page.getByTestId('log-filter-toolbar').getByRole('button', { name: '导出', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('restored-list-log-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`${process.env.E2E_BASE_URL}/#/rule/${config.definitionId}?focus=lifecycle`)
  await page.getByTestId('lifecycle-revision-selector').click()
  await page.getByRole('option').filter({ hasText: '已发布' }).click()
  const downloaded = page.waitForEvent('download')
  await page.getByTestId('download').click()
  const artifact = await downloaded
  expect(await artifact.failure()).toBeNull()
  await artifact.saveAs(testInfo.outputPath('restored-decision-artifact.zip'))
  expect(fs.readFileSync(testInfo.outputPath('restored-decision-artifact.zip')).subarray(0, 2).toString()).toBe('PK')
  expect(errors).toEqual([])
})

test('隔离备份恢复后从生产 dist 登录，规则结果和持久化回归证据仍正确', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_BASE_URL || !process.env.E2E_ISOLATED_OPTIMIZATION || !process.env.E2E_RUNTIME_ENV_FILE, '必须先完成本机隔离数据库恢复')
  test.setTimeout(120000)
  const config = JSON.parse(fs.readFileSync(process.env.E2E_RUNTIME_ENV_FILE, 'utf8'))
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await ui.login(page, '/test')
  const choice = page.locator('.el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: /^规则$/ }) }).locator('.el-select')
  await choice.click(); await choice.locator('input').fill(config.ruleCode)
  await page.getByRole('option').filter({ hasText: config.ruleCode }).click()
  const source = page.getByTestId('rule-test-source')
  await expect(source).toContainText('最新版（当前生产）')
  const executed = page.waitForResponse(response => response.url().endsWith('/api-scenarios/execute-validated') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '执行测试', exact: true }).click()
  const executionResponse = await (await executed).json()
  expect(executionResponse.code).toBe('000000')
  const execution = JSON.parse(executionResponse.data.responseJson).data
  expect(execution.success).toBe(true); expect(execution.result).toBe(45)
  await page.getByRole('button', { name: '回归报告', exact: true }).click()
  const reports = page.getByRole('dialog', { name: '回归报告', exact: true })
  await expect(reports.getByText('校验通过', { exact: true }).first()).toBeVisible()
  const checked = page.waitForResponse(response => response.url().endsWith('/reports/check') && response.request().method() === 'POST')
  await reports.getByRole('button', { name: '复核当前修订', exact: true }).click()
  const gate = await (await checked).json()
  expect(gate.code, gate.message).toBe('000000'); expect(gate.data.allowed).toBe(true); expect(gate.data.requiredCount).toBe(1)
  await page.screenshot({ path: testInfo.outputPath('restored-production-regression.png'), fullPage: true })
  await reports.locator('.el-drawer__close-btn').click()
  await page.goto(`${process.env.E2E_BASE_URL}/#/project/${config.projectId}`)
  await expect(page.locator('.layout-main')).toContainText(config.projectCode)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '名单管理', exact: true }).click()
  await expect(page.locator('.el-table__body').first()).toContainText('名单验收')
  fs.writeFileSync(testInfo.outputPath('restored-ui.json'), JSON.stringify({ result: execution.result, regressionAllowed: gate.data.allowed, fixedCases: gate.data.requiredCount }))
  expect(errors).toEqual([])
})
