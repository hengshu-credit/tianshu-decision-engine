const { test, expect } = require('@playwright/test')
const ui = require('./support/optimizationLive.cjs')
const { openRuleCaseTools, returnToRuleTest } = require('./support/ruleCaseTools.cjs')

test.beforeEach(() => test.skip(!process.env.E2E_ISOLATED_OPTIMIZATION || !process.env.E2E_BASE_URL, '需要独立验收环境'))

test('输入字段在线测试区分请求缺失和数值零', async ({ page }) => {
  test.setTimeout(120000)
  await ui.login(page, '/variable')
  const code = 'Amount_' + Date.now()
  await page.getByRole('button', { name: '新建字段', exact: true }).click()
  const form = page.getByRole('dialog', { name: '新建字段' })
  await form.locator('.el-form-item').filter({ hasText: '作用范围' }).locator('.el-select').click()
  await page.getByRole('option', { name: /全局/ }).click()
  await form.getByRole('textbox', { name: /字段编码$/ }).fill(code)
  await form.getByRole('textbox', { name: /字段名称$/ }).fill(code + '申请金额')
  await form.getByRole('textbox', { name: /脚本名称$/ }).fill(code)
  await form.locator('.el-form-item').filter({ hasText: '数据类型' }).locator('.el-select').click()
  await page.getByRole('option', { name: '数值 (NUMBER)', exact: true }).click()
  await form.getByRole('button', { name: '保存草稿' }).click()
  await expect(form).toBeHidden()
  await ui.submitRow(page, code); await ui.approve(page, code)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '变量管理', exact: true }).click()
  await page.getByRole('row').filter({ hasText: code }).getByRole('button', { name: '测试', exact: true }).click()
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('button', { name: '执行测试', exact: true }) })
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  for (const [params, explanation] of [[{}, '请求中缺少此字段'], [{ [code]: 0 }, '已取得最终值']]) {
    await dialog.getByTestId('variable-online-input').locator('[role="code"].monaco-editor').click()
    await page.keyboard.press('Control+A')
    await page.evaluate(value => navigator.clipboard.writeText(value), JSON.stringify(params))
    await page.keyboard.press('Control+V')
    await dialog.getByRole('button', { name: '执行测试', exact: true }).click()
    await expect(dialog.getByRole('status')).toContainText(explanation)
  }
  await expect(dialog.getByText('最终值', { exact: true }).locator('..')).toContainText('0')
})

test('已发布修订复跑固定用例，从执行流水查看费用并加载独立业务预期', async ({ page }) => {
  const rule = process.env.E2E_ACCEPTANCE_RULE
  test.skip(!rule, '需要已发布且有固定用例的 QL 规则')
  test.setTimeout(120000)
  await ui.login(page, '/test')
  const select = page.locator('.el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: /^规则$/ }) }).locator('.el-select')
  await select.click(); await select.locator('input').fill(rule)
  await page.getByRole('option').filter({ hasText: rule }).click()
  await expect(page.getByTestId('rule-test-source')).toContainText('生产')
  await openRuleCaseTools(page)
  await page.locator('.fixed-case-row').first().locator('.el-checkbox').click()
  await page.getByRole('button', { name: '批量执行', exact: true }).click()
  await expect(page.locator('.batch-result-table')).toContainText('校验通过')
  await returnToRuleTest(page)
  await page.getByRole('button', { name: '业务验收样例' }).click()
  const preview = page.getByRole('dialog', { name: '业务验收样例' })
  await expect(preview).toContainText('amount')
  await preview.getByRole('button', { name: '替换当前输入与预期' }).click()
  const execute = page.waitForResponse(r => r.url().endsWith('/execute-validated') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '执行测试', exact: true }).click()
  const response = (await (await execute).json()).data
  expect(response.execution.success).toBe(true)
  expect(response.validation.status).toBe('FAILED')
  await expect(page.getByText(/排查位置 ·/)).toContainText('字段引用')
  await page.getByRole('button', { name: '查看本次测试的设计版本' }).click()
  await expect(page).toHaveURL(new RegExp('/designer/script/' + response.execution.executionIdentity.definitionId + '\\?'))
  expect(new URLSearchParams(page.url().split('?')[1]).get('sourceId')).toBe(response.execution.executionIdentity.revisionId)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '执行日志', exact: true }).click()
  await page.getByPlaceholder('完整 trace_id').fill(response.execution.traceId)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await page.getByRole('row').filter({ hasText: response.execution.traceId }).getByRole('button', { name: '详情' }).click()
  await page.getByRole('tab', { name: '调用与费用' }).click()
  const panel = page.getByRole('region', { name: '按执行流水查看调用与费用' })
  await expect(panel).toContainText(response.execution.traceId)
  const bills = page.waitForResponse(r => r.url().includes('/record/by-trace?'))
  await panel.getByText('计费明细', { exact: true }).click()
  expect((await (await bills).json()).code).toBe('000000')
  await expect(panel).toContainText('金额')
})

test('从真实收费调用按流水核对单价、币种、合计和来源规则', async ({ page }) => {
  test.skip(!process.env.E2E_RUNTIME_ENV_FILE, '需要隔离项目及已发布规则')
  test.setTimeout(120000)
  const config = JSON.parse(require('node:fs').readFileSync(process.env.E2E_RUNTIME_ENV_FILE, 'utf8'))
  const name = '业务验收收费' + Date.now()
  await ui.login(page, '/billing')
  await page.getByRole('button', { name: '新建计费项' }).click()
  const form = page.getByRole('dialog', { name: '新建计费配置' })
  const project = form.locator('.el-form-item').filter({ hasText: '所属项目' }).locator('.el-select')
  await project.click(); await project.locator('input').fill(config.projectCode)
  await page.getByRole('option').filter({ hasText: config.projectCode }).click()
  await form.getByPlaceholder('如 ENGINE_COUNT').fill('Fee_' + Date.now())
  await form.getByPlaceholder('如 规则执行计费').fill(name)
  const target = form.locator('.el-form-item').filter({ hasText: '指定对象' }).locator('.el-select')
  await target.click(); await target.locator('input').fill(config.ruleCode)
  await page.getByRole('option').filter({ hasText: config.ruleCode }).click()
  await form.getByRole('spinbutton').fill('0.012345')
  await form.getByRole('button', { name: /保存|确定/ }).click()
  await expect(form).toBeHidden()
  await ui.submitRow(page, name); await ui.approve(page, name)
  const call = await page.request.post(process.env.E2E_BASE_URL + '/api/rule/sync/execute/' + config.ruleCode, {
    headers: { 'X-Rule-Api-Key': config.apiKey }, data: { params: {} },
  })
  const data = (await call.json()).data
  expect(data.success).toBe(true)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '执行日志', exact: true }).click()
  await page.getByPlaceholder('完整 trace_id').fill(data.traceId)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await page.getByRole('row').filter({ hasText: data.traceId }).getByRole('button', { name: '详情' }).click()
  await page.getByRole('tab', { name: '调用与费用' }).click()
  const panel = page.getByRole('region', { name: '按执行流水查看调用与费用' })
  await panel.getByText('计费明细', { exact: true }).click()
  await expect(panel.getByText('已入账合计 0.012345 CNY')).toBeVisible()
  await panel.getByRole('row').filter({ hasText: name }).getByRole('link').click()
  await expect(page).toHaveURL(new RegExp('/rule/' + config.definitionId + '(?:\\?|$)'))
})
