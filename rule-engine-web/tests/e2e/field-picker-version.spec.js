const { expect, test } = require('@playwright/test')
const { installDistRoutes } = require('./support/distRoutes.cjs')
const { createDesignerApiData } = require('./support/designerFixtures.cjs')

for (const colorScheme of ['LIGHT', 'DARK']) test(`${colorScheme} 指定版本、修改版本、已选定位与搜索保留`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.addInitScript(scheme => localStorage.setItem('tianshu-ui-theme-v1', JSON.stringify({ schemaVersion: 1, colorScheme: scheme, accentPreset: 'THEME_BLUE', sidebarTheme: 'DARK', contentWidth: 'FLUID', fixedSidebar: true, colorWeak: false })), colorScheme)
  const data = createDesignerApiData()
  data.set('/api/rule/variable/picker-versions/1', [{ versionId: '203', version: 3 }, { versionId: '9007199254740993', version: 2 }])
  data.set('/api/rule/variable/picker-version/9007199254740993', { versionId: '9007199254740993', version: 2, versionOwnerId: '1', refId: '1', refType: 'VARIABLE', code: 'age_before', label: '历史年龄', valueType: 'INTEGER', varSource: 'INPUT' })
  const { requests, assertClean } = await installDistRoutes(page, { apiData: data })
  await page.goto('http://tianshu.local/index.html#/designer/table/101')
  await page.getByRole('button', { name: '添加行', exact: true }).click()
  const field = page.getByPlaceholder('选择左操作数...')
  await field.click()
  const panel = page.locator('.fp-panel:visible')
  await expect(panel.getByRole('toolbar', { name: '配置面板' })).toBeVisible()
  expect(requests.some(request => request.url.includes('picker-versions'))).toBe(false)
  const row = panel.getByRole('row').filter({ has: page.getByRole('gridcell', { name: '年龄', exact: true }) })
  await row.locator('.fp-version-select .el-select__wrapper').click()
  await page.getByRole('option', { name: 'v2', exact: true }).click()
  const historical = panel.getByRole('row').filter({ hasText: '历史年龄' })
  await historical.dblclick()
  await expect(panel).toHaveCount(0)
  await expect(field).toHaveValue('历史年龄 age_before')
  await expect(page.locator('.vp-input-version')).toHaveText('v2')
  await field.click()
  await expect(panel.getByRole('row', { selected: true })).toContainText('历史年龄')
  await panel.getByRole('textbox', { name: '搜索字段名称或编码' }).fill('age')
  await panel.getByRole('button', { name: /^常量/ }).click()
  await expect(panel.getByRole('textbox', { name: '搜索字段名称或编码' })).toHaveValue('age')
  await panel.getByRole('button', { name: /^变量/ }).click()
  await panel.getByRole('row').filter({ hasText: '历史年龄' }).locator('.fp-version-select .el-select__wrapper').click()
  await page.getByRole('option', { name: '最新·v3', exact: true }).click()
  await expect(field).toHaveValue('年龄 age')
  await expect(page.locator('.vp-input-version')).toHaveText('最新·v3')
  const preview = panel.locator('.fp-preview')
  await panel.getByRole('row').filter({ has: page.getByRole('gridcell', { name: '年龄', exact: true }) }).click()
  await expect(preview).toHaveAttribute('title', /年龄.*age.*INTEGER/)
  expect(await preview.evaluate(element => getComputedStyle(element).whiteSpace)).toBe('nowrap')
  await expect(page.getByRole('listbox', { name: '选择字段版本' })).toBeHidden()
  await page.screenshot({ path: testInfo.outputPath(`field-version-${colorScheme.toLowerCase()}.png`) })
  assertClean()
})
