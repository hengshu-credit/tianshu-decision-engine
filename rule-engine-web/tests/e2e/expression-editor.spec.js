async function openExpressionFromPicker(page) {
  await expect(page.getByRole('button', { name: '配置组合表达式', exact: true })).toHaveCount(0)
  await page.getByPlaceholder('选择左操作数...').first().click()
  await page.locator('.fp-panel:visible').getByRole('button', { name: 'ƒx 组合表达式', exact: true }).click()
}

function dataWithExpressionFunctions() {
  const data = createDesignerApiData()
  data.set('/api/rule/function/project/1/all', [
    { id: 801, funcCode: 'objGet', funcName: '对象路径取值', returnType: 'OBJECT', paramsJson: JSON.stringify([{ name: 'object', type: 'OBJECT', example: { customer: { age: 18 } } }, { name: 'path', type: 'STRING', example: 'customer.age' }]) },
    { id: 802, funcCode: 'toNumberValue', funcName: '转换为数值', returnType: 'NUMBER', paramsJson: JSON.stringify([{ name: 'value', type: 'OBJECT', example: '12.5' }]) },
    { id: 803, funcCode: 'arrGet', funcName: '数组按下标取值', returnType: 'OBJECT', paramsJson: JSON.stringify([{ name: 'values', type: 'LIST', example: ['A', 'B', 'C'] }, { name: 'index', type: 'NUMBER', example: 1 }]) },
  ])
  return data
}

