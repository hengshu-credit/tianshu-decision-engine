const { test, expect } = require('@playwright/test')
const fs = require('node:fs')
const base = process.env.E2E_BASE_URL
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })

test('真实 UI 修改规则使回归证据失效，重新回归发布后独立运行时更新', async ({ page }, testInfo) => {
  test.skip(!base || !process.env.E2E_ISOLATED_OPTIMIZATION || !process.env.E2E_RUNTIME_ENV_FILE, '需要本机隔离验收生成的已发布规则')
  test.setTimeout(180000)
  const config = JSON.parse(fs.readFileSync(process.env.E2E_RUNTIME_ENV_FILE, 'utf8'))
  const value = Number(process.env.E2E_UPDATED_RESULT || 43)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${base}/#/designer/script/${config.definitionId}?projectId=${config.projectId}`)
  await page.locator('input[autocomplete="username"]').fill(process.env.E2E_USERNAME)
  await page.locator('input[autocomplete="current-password"]').fill(process.env.E2E_PASSWORD)
  await page.locator('button[type="submit"]').click()
  await expect(page.getByTestId('designer-version-select')).toContainText('生产 ·')
  await page.locator('.monaco-editor').first().click(); await page.keyboard.press('Control+A'); await page.keyboard.insertText(`return ${value};`)
  const saved = page.waitForResponse(response => response.url().includes('/designer/drafts') && response.request().method() === 'POST')
  await page.locator('.rule-designer-actions [data-action="save"]').click()
  const body = await (await saved).json(); expect(body.code).toBe('000000')
  const revision = body.data.revision
  await expect(page).toHaveURL(new RegExp('sourceId=' + revision.id))
  const designerUrl = page.url()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '规则测试', exact: true }).click()
  const choice = page.locator('.el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: /^规则$/ }) }).locator('.el-select')
  await choice.click(); await choice.locator('input').fill(config.ruleCode)
  await page.getByRole('option').filter({ hasText: config.ruleCode }).click()
  await expect(page.getByTestId('rule-test-source')).toContainText(/当前生产|草稿/)
  await page.getByTestId('rule-test-source').click()
  await page.getByRole('option', { name: new RegExp('草稿\\s*' + revision.revisionNo) }).click()
  const fixed = page.locator('.fixed-case-row').first()
  await fixed.getByRole('button', { name: '载入', exact: true }).click()
  await fixed.locator('.el-checkbox__label').click()
  await page.getByRole('button', { name: '批量执行', exact: true }).click()
  await expect(page.locator('.batch-result-table')).toContainText('预期不符', { timeout: 20000 })
  const execute = page.waitForResponse(response => response.url().endsWith('/execute-validated') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '执行测试', exact: true }).click()
  const actual = await (await execute).json()
  expect(actual.data.execution.success).toBe(true); expect(actual.data.execution.result).toBe(value)
  await page.getByTestId('expectation-use-actual').click()
  await page.getByRole('button', { name: '保存当前用例', exact: true }).click()
  await expect(page.getByText('测试用例已更新', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '回归报告', exact: true }).click()
  const checked = page.waitForResponse(response => response.url().endsWith('/reports/check') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '复核当前修订', exact: true }).click()
  const gate = (await (await checked).json()).data
  expect(gate.allowed).toBe(false); expect(gate.staleCount).toBe(1)
  await page.screenshot({ path: testInfo.outputPath('updated-case-invalidates-evidence.png'), fullPage: true })
  await page.getByRole('dialog', { name: '回归报告', exact: true }).locator('.el-drawer__close-btn').click()
  await page.getByRole('button', { name: '批量执行', exact: true }).click()
  await expect(page.locator('.batch-result-table')).toContainText('校验通过', { timeout: 20000 })
  await page.goto(designerUrl)
  await page.locator('.rule-designer-actions [data-action="publish"]').click()
  const submission = page.waitForResponse(response => response.url().includes('/designer/publish') && response.request().method() === 'POST')
  await page.locator('[data-action="confirm-publish"]').click()
  const submitted = await (await submission).json(); expect(submitted.code, submitted.message).toBe('000000')
  await page.locator('[data-action="view-approval"]').click()
  await page.getByRole('button', { name: '通过并生效', exact: true }).click()
  await page.getByRole('dialog', { name: '通过并立即生效', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.locator('.header-meta')).toContainText('已通过', { timeout: 30000 })
  if (process.env.E2E_SKIP_RUNTIME_PROBE !== 'true') {
    await expect.poll(async () => {
      const response = await page.request.post(`http://127.0.0.1:17071/api/rule/execute/${config.ruleCode}`, { headers: { authorization: 'Bearer ' + config.runtimeToken }, data: { params: {} } })
      return (await response.json()).data?.result
    }, { timeout: 15000, message: '发布后 SDK 运行时必须收到新版本' }).toBe(value)
  }
  fs.writeFileSync(testInfo.outputPath('runtime-rule-update.json'), JSON.stringify({ definitionId: config.definitionId, revisionId: revision.id, value }))
  expect(errors).toEqual([])
})
