const { test, expect } = require('@playwright/test')
const fs = require('node:fs')
const path = require('node:path')
const ui = require('./support/optimizationLive.cjs')
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })

test('真实 HTTP 外数 UI 配置、响应样例、缓存、空响应与失败反馈', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_BASE_URL || !process.env.E2E_ISOLATED_OPTIMIZATION, '仅连接本机隔离 HTTP 夹具')
  test.setTimeout(180000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  page.on('response', async response => {
    if (response.url().includes('/api/') && response.status() >= 400) {
      const body = await response.json().catch(() => ({}))
      console.error('API failure', response.request().method(), new URL(response.url()).pathname, response.status(), body.code, body.message)
    }
  })
  const sourceName = `外数验收${Date.now()}`, apiName = `评分查询${Date.now()}`, apiCode = `Score_${Date.now()}`
  await ui.login(page, '/datasource')
  await page.getByRole('button', { name: '新建数据源', exact: true }).click()
  await expect(page).toHaveURL(/#\/datasource\/source\/new/)
  await expect(page.getByTestId('save-external-datasource')).toBeEnabled()
  await page.locator('.detail-form .el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: '作用范围' }) }).locator('.el-select').click()
  await page.getByRole('option', { name: '全局', exact: true }).click()
  await page.getByRole('textbox', { name: /数据源编码$/ }).fill(`Provider_${Date.now()}`)
  await page.getByRole('textbox', { name: /数据源名称$/ }).fill(sourceName)
  await page.getByRole('textbox', { name: /基础地址$/ }).fill('http://127.0.0.1:18091')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText(/草稿已保存/).first()).toBeVisible()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '外数管理', exact: true }).click()
  await ui.submitRow(page, sourceName); await ui.approve(page, sourceName)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '外数管理', exact: true }).click()
  await page.getByRole('tab', { name: 'API 接口', exact: true }).click()
  await page.getByRole('button', { name: '新建接口', exact: true }).click()
  await expect(page).toHaveURL(/#\/datasource\/api\/new/)
  await expect(page.getByRole('textbox', { name: /接口编码$/ })).toBeVisible()
  const source = page.locator('.el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: '所属数据源' }) }).locator('.el-select')
  await source.click(); await source.locator('input').fill(sourceName)
  await page.getByRole('option').filter({ hasText: sourceName }).click()
  await page.getByRole('textbox', { name: /接口编码$/ }).fill(apiCode)
  await page.getByRole('textbox', { name: /接口名称$/ }).fill(apiName)
  await page.getByRole('textbox', { name: /接口地址$/ }).fill('/sample')
  await page.getByRole('tab', { name: '响应结构', exact: true }).click()
  await page.getByRole('button', { name: '添加响应条件分支', exact: true }).click()
  await page.getByRole('button', { name: '导入响应样例生成字段', exact: true }).click()
  const sample = page.getByRole('dialog', { name: '导入响应样例', exact: true })
  await sample.getByText('整体取值', { exact: true }).click()
  const editor = sample.getByRole('textbox', { name: /Editor content/ })
  await editor.click(); await editor.press('Control+A'); await editor.press('Backspace'); await editor.fill('{"score":88,"status":"ok"}')
  await expect(editor).toHaveValue('{"score":88,"status":"ok"}')
  await sample.getByRole('button', { name: '生成结构', exact: true }).click()
  await expect(sample).toBeHidden()
  await page.getByRole('button', { name: /^稳定性策略/ }).click()
  await page.getByRole('tab', { name: '缓存&计费', exact: true }).click()
  await page.getByRole('spinbutton', { name: '响应缓存秒', exact: true }).fill('60')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page).toHaveURL(/#\/datasource\/api\/\d+/)
  const apiId = page.url().match(/\/api\/(\d+)/)[1]
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '外数管理', exact: true }).click()
  await page.getByRole('tab', { name: 'API 接口', exact: true }).click()
  await ui.submitRow(page, apiName); await ui.approve(page, apiName)
  await page.goto(`${process.env.E2E_BASE_URL}/#/datasource/api/${apiId}`)
  await expect(page.getByRole('textbox', { name: /接口编码$/ })).toHaveValue(apiCode)
  await page.getByRole('button', { name: /^业务配置/ }).click()
  await page.getByRole('tab', { name: '接口测试', exact: true }).click()
  await expect(page.getByText(/可能产生供应商费用或触发业务副作用/)).toBeVisible()
  await page.request.post('http://127.0.0.1:18091/reset')
  const invoke = async () => {
    const response = page.waitForResponse(item => item.url().endsWith('/invoke-preview') && item.request().method() === 'POST')
    await page.getByRole('button', { name: '执行测试', exact: true }).click()
    return (await response).json()
  }
  const live = await invoke(); expect(live.code, live.message).toBe('000000'); expect(live.data.body.score).toBe(88)
  await expect(page.getByText(/当前配置测试不读取或写入响应缓存/)).toBeVisible()
  const repeated = await invoke(); expect(repeated.code).toBe('000000'); expect(repeated.data.dataOrigin).toBe('LIVE')
  expect((await (await page.request.get('http://127.0.0.1:18091/stats')).json()).count).toBe(2)
  await page.getByRole('textbox', { name: /接口地址$/ }).fill('/empty')
  await expect(page.getByText('配置或参数已变化，下面是此前的调用结果，请重新测试。', { exact: true })).toBeVisible()
  const empty = await invoke(); expect(empty.code).toBe('000000'); expect(empty.data.body).toEqual({})
  await page.getByRole('textbox', { name: /接口地址$/ }).fill('/fail')
  const failed = await invoke(); expect(failed.code).not.toBe('000000'); expect(failed.data?.success).toBe(false)
  await page.getByRole('textbox', { name: /接口地址$/ }).fill('/sample')
  await page.reload(); await expect(page.getByRole('textbox', { name: /接口地址$/ })).toHaveValue('/sample')
  await page.screenshot({ path: testInfo.outputPath('external-saved-api.png'), fullPage: true })
  fs.writeFileSync(testInfo.outputPath('external-results.json'), JSON.stringify({ liveOrigin: live.data.dataOrigin, repeatedOrigin: repeated.data.dataOrigin, empty: empty.data.body, failureCode: failed.code }))
  if (process.env.E2E_RUNTIME_ENV_FILE) fs.writeFileSync(path.join(path.dirname(process.env.E2E_RUNTIME_ENV_FILE), 'external-ui-fixture.json'), JSON.stringify({ apiId, apiCode, apiName, sourceName }))
  expect(errors).toEqual([])
})
