const { expect, test } = require('@playwright/test')
const { installDistRoutes } = require('./support/distRoutes.cjs')
const { createManagementApiData } = require('./support/managementFixtures.cjs')
const { createDetailApiData } = require('./support/detailFixtures.cjs')

test('API 请求字段分别配置位置、格式和文件内容，窄窗口只滚动表格', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  const apiData = createDetailApiData()
  apiData.set('/api/rule/governance/workspaces/EXTERNAL_API/22', {})
  apiData.set('/api/rule/variable/source-options', { apiOptions: [], dbOptions: [], listOptions: [] })
  const api = apiData.get('/api/rule/datasource/api-config/22')
  api.executionConfig = JSON.stringify({ version: 2, requestFields: [
    { id: 'body', path: 'Customer.Mobile', location: 'JSON', value: { kind: 'LITERAL', value: 'sample' } },
    { id: 'query', path: 'page', location: 'QUERY', value: { kind: 'LITERAL', value: 1 } },
  ] })
  const { assertClean } = await installDistRoutes(page, { apiData })
  await page.goto('http://tianshu.local/index.html#/datasource/api/22')
  await page.getByRole('tab', { name: '请求字段', exact: true }).click()
  const editor = page.locator('.api-execution-editor:visible')
  await expect(editor.getByRole('columnheader', { name: '字段位置', exact: true })).toBeVisible()
  await expect(editor.getByRole('columnheader', { name: '数据格式', exact: true })).toBeVisible()
  await expect(editor.getByRole('columnheader', { name: '字段内容', exact: true })).toHaveCount(0)
  const row = editor.locator('.el-table__body .el-table__row').first()
  await row.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '请求体格式', exact: true }) }).click()
  await page.getByRole('option', { name: 'x-www-form-urlencoded', exact: true }).click()
  await row.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '字段内容', exact: true }) }).click()
  await page.getByRole('option', { name: '压缩后转 Base64', exact: true }).click()
  await row.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '字段位置', exact: true }) }).click()
  await expect(page.getByRole('option', { name: 'Headers', exact: true })).toHaveAttribute('aria-disabled', 'true')
  await page.keyboard.press('Escape')
  await row.getByRole('button', { name: '展开当前行', exact: true }).click()
  await expect(editor.getByPlaceholder('ZIP 内文件名，例如 application.pdf')).toBeVisible()
  await expect(row.locator('input[placeholder="如 mobile"]')).toHaveValue('Customer.Mobile')
  const geometry = await editor.evaluate(element => ({ client: element.clientWidth, scroll: element.scrollWidth }))
  expect(geometry.scroll).toBeLessThanOrEqual(geometry.client + 1)
  assertClean()
})

for (const mode of ['INPUT', 'FIELDS']) {
  test(`接口变量通过统一选择器配置 ${mode} 入参覆盖和响应子字段`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 1000 })
    const apiData = createManagementApiData()
    const age = { id: 1, varCode: 'age', varLabel: '年龄', varType: 'STRING', varSource: 'INPUT', scope: 'PROJECT', projectId: 1, status: 1 }
    apiData.set('/api/rule/project/1', { id: 1, projectCode: 'e2e_project', projectName: 'E2E 项目', status: 1 })
    apiData.set('/api/rule/variable/project/1', [age])
    apiData.set('/api/rule/dataobject/tree/1', { tree: [] })
    apiData.set('/api/rule/function/project/1/all', [])
    apiData.set('/api/rule/model/project/1/all', [])
    apiData.set('/api/rule/variable/source-options', { apiOptions: [{ id: 22, name: '征信查询', code: 'credit_query' }], dbOptions: [], listOptions: [] })
    apiData.set('/api/rule/datasource/api-config/22/binding-contract', {
      bindingMode: mode, apiName: '征信查询',
      inputFields: [{ id: 'customer.age', path: 'customer.age', location: 'INPUT', overridable: true }],
      requestFields: [{ id: 'field-1', path: 'customer.age', location: 'JSON', overridable: true }, { id: 'locked', path: 'product', location: 'JSON', overridable: false }],
      resultFields: [{ value: 'body.features.score', label: '评分', type: 'NUMBER' }],
    })
    let preview
    apiData.set('POST /api/rule/variable/preview', ({ request }) => { preview = request.postDataJSON(); return { value: 80 } })
    const { assertClean } = await installDistRoutes(page, { apiData })
    await page.goto('http://tianshu.local/index.html#/variable?projectId=1')
    await page.getByRole('button', { name: '新建字段', exact: true }).click()
    const dialog = page.locator('.el-dialog:visible').last()
    await dialog.locator('.el-form-item').filter({ hasText: /^字段编码/ }).getByRole('textbox').fill('api_score')
    await dialog.locator('.el-form-item').filter({ hasText: /^字段名称/ }).getByRole('textbox').fill('接口评分')
    await dialog.getByRole('button', { name: /外数接口/ }).click()
    await dialog.locator('.el-form-item').filter({ hasText: /^接口配置/ }).getByRole('textbox').click()
    await page.locator('.fp-panel:visible .fp-row').filter({ hasText: 'credit_query' }).dblclick()
    const binding = dialog.locator('.api-source-binding')
    await expect(binding.getByRole('columnheader', { name: '覆盖位置', exact: true })).toBeVisible()
    await expect(binding.getByRole('columnheader', { name: '数据格式', exact: true })).toBeVisible()
    await expect(binding.getByRole('cell', { name: mode === 'INPUT' ? '调用入参' : 'Body', exact: true }).first()).toBeVisible()
    await expect(binding.getByRole('cell', { name: mode === 'INPUT' ? '由 API 映射' : 'JSON', exact: true }).first()).toBeVisible()
    await expect(binding.getByRole('cell', { name: 'customer.age', exact: true })).toBeVisible()
    if (mode === 'FIELDS') await expect(binding.getByText('未开放', { exact: true })).toBeVisible()
    await binding.locator('.el-checkbox[aria-label="覆盖 customer.age"]').click()
    await binding.locator('.api-value-editor').getByRole('textbox').click()
    let picker = page.locator('.fp-panel:visible')
    await picker.getByRole('textbox', { name: '搜索字段名称或编码' }).fill('age')
    await picker.locator('.fp-row').filter({ hasText: '年龄' }).dblclick()
    await expect(binding.locator('.api-value-editor input')).toHaveValue(/年龄/)
    await expect(picker).toHaveCount(0)
    await binding.locator('.api-binding-result-picker').getByRole('textbox').click()
    picker = page.locator('.fp-panel:visible')
    await picker.getByRole('textbox', { name: '搜索字段名称或编码' }).fill('body.features.score')
    await picker.locator('.fp-row').filter({ hasText: 'body.features.score' }).dblclick()
    await expect(binding.locator('.api-binding-result-picker input')).toHaveValue(/评分|body.features.score/)
    await dialog.getByRole('button', { name: '真实调用测试', exact: true }).click()
    await expect.poll(() => preview).toBeTruthy()
    const source = JSON.parse(preview.variable.sourceConfig)
    const overrides = mode === 'INPUT' ? source.inputOverrides : source.requestOverrides
    expect(String(overrides[mode === 'INPUT' ? 'customer.age' : 'field-1'].refId)).toBe('1')
    expect(source.resultPath).toBe('body.features.score')
    expect(source.apiConfigId).toBe(22)
    await dialog.locator('.el-dialog__headerbtn').click()
    assertClean()
  })
}
