async function chooseReference(page, input, keyword) {
  await input.click()
  const picker = page.locator('.fp-panel:visible')
  await picker.getByRole('textbox', { name: '搜索字段名称或编码' }).fill(keyword)
  await picker.locator('.fp-row').filter({ hasText: keyword }).last().dblclick()
}

async function typeMonaco(page, editor, text) {
  await editor.locator('.view-lines').click()
  await page.keyboard.press('Control+Home')
  await page.keyboard.press('Control+Shift+End')
  await page.keyboard.press('Backspace')
  await page.keyboard.insertText(text)
  await expect(editor.getByRole('textbox')).toHaveValue(text)
}

