for (const [model, route] of [['决策树', 'tree'], ['决策流', 'flow']]) {
  test(`真实${model}从锚点编排动作和结束节点，保存重载并执行`, async ({ page }, testInfo) => {
    test.setTimeout(120000)
    const config = JSON.parse(fs.readFileSync(configFile, 'utf8')), fixture = JSON.parse(fs.readFileSync(fixturePath(), 'utf8'))
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width: 1600, height: 1000 })
    await ui.login(page, '/project'); await ui.createRule(page, config.projectId, model)
    const nodes = page.locator(`.${route}-canvas .lf-node:not(.lf-mini-map .lf-node)`)
    const addConnected = async (index, label) => {
      const node = nodes.nth(index)
      await node.hover()
      const anchors = node.locator('.lf-anchor:visible')
      await expect(anchors.first()).toBeVisible()
      const positions = await anchors.evaluateAll(elements => elements.map((element, index) => ({ index, x: element.getBoundingClientRect().x })))
      positions.sort((a, b) => b.x - a.x)
      await anchors.nth(positions[0].index).click()
      await page.locator('.flow-node-add-menu').getByRole('button', { name: label, exact: true }).click()
    }
    await expect(nodes).toHaveCount(1)
    await addConnected(0, '执行动作')
    await expect(nodes).toHaveCount(2)
    await addConnected(1, '结束')
    await page.getByRole('dialog', { name: '添加结束节点', exact: true }).getByRole('button', { name: '确认添加', exact: true }).click()
    await expect(nodes).toHaveCount(3)
    await nodes.nth(1).click()
    const panel = page.locator(`.${route}-property`)
    await panel.getByRole('button', { name: '添加动作块', exact: true }).click()
    await page.getByRole('menuitem', { name: '赋值', exact: true }).click()
    await ui.field(page, panel.getByPlaceholder('选择目标字段'), fixture.outputCode)
    await ui.literal(page, panel.getByPlaceholder('选择值或字段'), 7)
    const saved = await ui.save(page)
    const graph = JSON.parse(saved.revision.modelJson)
    expect(graph.nodes).toHaveLength(3); expect(graph.edges).toHaveLength(2)
    expect((await ui.execute(page)).result[fixture.outputCode]).toBe(7)
    await page.reload(); await expect(nodes).toHaveCount(3)
    expect((await ui.execute(page)).result[fixture.outputCode]).toBe(7)
    await page.screenshot({ path: testInfo.outputPath('graph-saved-reloaded.png'), fullPage: true })
    expect(errors).toEqual([])
  })
}
