const { test, expect } = require('@playwright/test')
const { createDesignerApiData } = require('./support/designerFixtures.cjs')
const { createManagementApiData } = require('./support/managementFixtures.cjs')
const { installDistRoutes } = require('./support/distRoutes.cjs')

test('衍生统计的主体字段与聚合函数也使用内容选择器', async ({ page }) => {
  const data = createManagementApiData()
  data.set('/api/rule/variable/source-options', { apiOptions: [], databaseOptions: [], listOptions: [], sftpOptions: [] })
  data.set('/api/rule/variable/project/1', [{ id: '77', varCode: 'address', varLabel: '地址', varType: 'STRING', varSource: 'INPUT', version: 3 }])
  data.set('/api/rule/dataobject/tree/1', [])
  data.set('/api/rule/model/project/1/all', [])
  data.set('/api/rule/function/project/1/all', [{ id: '78', funcCode: 'statValues', funcName: '统计列表', returnType: 'NUMBER', version: 2 }])
  const origin = process.env.E2E_DEV_BASE_URL || 'http://tianshu.local'
  const { assertClean } = await installDistRoutes(page, { apiData: data, origin, liveStatic: !!process.env.E2E_DEV_BASE_URL })
  await page.goto(`${origin}/#/variable?projectId=1`)
  await page.getByRole('button', { name: '新建字段', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建字段', exact: true })
  await dialog.getByRole('button', { name: /衍生变量/ }).click()
  await dialog.getByText('内部进件统计', { exact: true }).click()
  await dialog.getByPlaceholder('选择主体字段，可添加联合字段', { exact: true }).click()
  const picker = page.locator('.fp-panel:visible')
  await picker.getByRole('row').filter({ has: page.getByRole('gridcell', { name: 'address', exact: true }) }).dblclick()
  await expect(dialog.locator('.subject-field .content-ref__source')).toHaveText('变量')
  await expect(dialog.locator('.subject-field .content-ref__type')).toHaveText('Abc')
  await expect(dialog.locator('.subject-field')).toContainText('地址address')
  await dialog.locator('.el-form-item').filter({ hasText: /^统计方法/ }).locator('.el-select').click()
  await page.getByRole('option', { name: '自定义函数（接收值列表）', exact: true }).click()
  await dialog.getByPlaceholder('函数接收一个统计值列表', { exact: true }).click()
  await picker.getByRole('row').filter({ has: page.getByRole('gridcell', { name: 'statValues', exact: true }) }).dblclick()
  const fn = dialog.locator('.el-form-item').filter({ hasText: /^聚合函数/ })
  await expect(fn.locator('.content-ref__source')).toHaveText('方法')
  await expect(fn.locator('.content-ref__type')).toHaveText('N')
  await expect(fn.locator('input')).toHaveValue('统计列表 statValues')
  await expect(fn.locator('.content-ref__version')).toContainText('v2')
  assertClean()
})

test('内容选择器与 fx 统一展示来源类型图标，整行运算按左值过滤并支持无右值', async ({ page }, testInfo) => {
  const data = createDesignerApiData()
  data.get('/api/rule/variable/project/1').push({ id: '77', varCode: 'address', varLabel: '地址', varType: 'STRING', varSource: 'INPUT', version: 3 })
  const origin = process.env.E2E_DEV_BASE_URL || 'http://tianshu.local'
  const { assertClean } = await installDistRoutes(page, { apiData: data, origin, liveStatic: !!process.env.E2E_DEV_BASE_URL })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`${origin}/#/designer/table/101`)
  await page.getByRole('button', { name: '添加行', exact: true }).click()
  const field = page.getByPlaceholder('选择左操作数...').first()
  await field.click()
  await page.locator('.fp-panel:visible').getByRole('button', { name: 'ƒx 组合表达式', exact: true }).click()
  const editor = page.locator('.expression-editor--compact:visible')
  const child = page.locator('.fp-panel:visible').filter({ hasNot: editor })
  await editor.locator('.canvas-node').click()
  await child.getByRole('textbox', { name: '搜索内容名称或编码' }).fill('address')
  await child.getByRole('row').filter({ has: page.getByRole('gridcell', { name: 'address', exact: true }) }).dblclick()
  await expect(editor.locator('.canvas-node .content-ref__source')).toHaveText('变量')
  await expect(editor.locator('.canvas-node .content-ref__type')).toHaveText('Abc')
  await expect(editor.locator('.canvas-node .content-ref')).toContainText('地址address')
  await expect(editor.locator('.canvas-node .content-ref')).toContainText('v3')
  const segments = await editor.locator('.canvas-node .content-ref').evaluate(element => [...element.children].map(child => ({ key: child.dataset.contentPart, x: child.getBoundingClientRect().x, right: child.getBoundingClientRect().right, background: getComputedStyle(child).backgroundColor })))
  expect(segments.map(part => part.key)).toEqual(['source', 'type', 'name', 'code', 'version'])
  for (let i = 1; i < segments.length; i++) expect(Math.abs(segments[i].x - segments[i - 1].right)).toBeLessThanOrEqual(0.5)
  expect(new Set(segments.map(part => part.background)).size).toBeGreaterThanOrEqual(4)
  await editor.getByRole('button', { name: '添加运算项', exact: true }).click()
  await child.getByRole('textbox', { name: '搜索内容名称或编码' }).fill('address')
  await child.getByRole('row').filter({ has: page.getByRole('gridcell', { name: 'address', exact: true }) }).dblclick()
  const operator = editor.locator('.canvas-edge-operator')
  const row = editor.locator('.canvas-operator-row')
  expect((await operator.boundingBox()).width).toBeGreaterThan((await row.boundingBox()).width - 2)
  expect((await operator.boundingBox()).height).toBeGreaterThanOrEqual(40)
  await operator.click()
  await expect(page.getByRole('menuitem', { name: /^包含 contains$/ })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: /^减 / })).toHaveCount(0)
  await page.getByRole('menuitem', { name: /^为空字符串 is_empty$/ }).click()
  await expect(editor.locator('.canvas-node')).toHaveCount(1)
  await expect(operator).toContainText('无需右值')
  await expect(editor.getByRole('region', { name: '表达式预览' })).toContainText('isBlank(address)')
  await page.screenshot({ path: testInfo.outputPath('content-unary.png'), animations: 'disabled' })
  await operator.click()
  await page.getByRole('menuitem', { name: /^包含 contains$/ }).click()
  await expect(editor.locator('.canvas-node')).toHaveCount(2)
  await editor.locator('.canvas-node--empty').click()
  await child.getByRole('button', { name: '输入阈值', exact: true }).click()
  await child.getByRole('textbox', { name: /^阈值内容/ }).fill('上海')
  await child.getByRole('button', { name: '应用阈值', exact: true }).click()
  await expect(editor.locator('.canvas-node .content-ref__type')).toHaveText(['Abc', 'Abc'])
  await expect(editor.locator('.canvas-node .content-ref__source')).toHaveText(['变量', '阈值'])
  for (const badge of await editor.locator('.canvas-node .content-ref__source, .canvas-node .content-ref__type').all()) {
    await expect(badge).toHaveCSS('width', '32px')
    await expect(badge).toHaveCSS('height', '20px')
  }
  await expect(child).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('content-expression.png'), animations: 'disabled' })
  await editor.getByRole('button', { name: '应用公式', exact: true }).click()
  const input = field.locator('xpath=ancestor::div[contains(@class,"vp-reference")]')
  await expect(input.locator('.content-ref__source')).toHaveText('运算')
  await expect(input.locator('.content-ref__type')).toHaveText('T/F')
  await expect(input.locator('.content-ref__source')).toHaveCSS('width', '32px')
  await expect(input.locator('.content-ref__type')).toHaveCSS('width', '32px')
  await expect(field).toHaveValue(/包含/)
  assertClean()
})
