const { test, expect } = require('@playwright/test')
const fs = require('node:fs')
const path = require('node:path')
const ui = require('./support/optimizationLive.cjs')
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })

test('通过 UI 建立外数字段与规则，核对真实缓存和根 trace 的模块日志', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_BASE_URL || !process.env.E2E_ISOLATED_OPTIMIZATION || !process.env.E2E_RUNTIME_ENV_FILE, '需要本机隔离 HTTP 服务和 UI 创建的 API')
  test.setTimeout(180000)
  const directory = path.dirname(process.env.E2E_RUNTIME_ENV_FILE)
  const api = JSON.parse(fs.readFileSync(path.join(directory, 'external-ui-fixture.json'), 'utf8'))
  const runtime = JSON.parse(fs.readFileSync(process.env.E2E_RUNTIME_ENV_FILE, 'utf8'))
  const code = `Source_Score_${Date.now()}`
  await ui.login(page, '/variable')
  await page.getByRole('button', { name: '新建字段', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建字段', exact: true })
  await dialog.locator('.el-form-item').filter({ hasText: '作用范围' }).locator('.el-select').click()
  await page.getByRole('option', { name: /全局/ }).click()
  for (const label of ['字段编码', '字段名称', '脚本名称']) await dialog.getByRole('textbox', { name: new RegExp(label + '$') }).fill(code)
  await dialog.locator('.el-form-item').filter({ hasText: '数据类型' }).locator('.el-select').click()
  await page.getByRole('option', { name: '数值 (NUMBER)', exact: true }).click()
  await dialog.getByRole('button', { name: /外数接口/ }).click()
  await ui.field(page, dialog.locator('.el-form-item').filter({ hasText: '接口配置' }).locator('input'), api.apiCode)
  const resultPath = dialog.getByPlaceholder('选择模块、子字段或输入路径')
  await resultPath.fill('body.score'); await dialog.getByText('字段编码', { exact: true }).click()
  await expect(resultPath).toHaveValue('body.score')
  await dialog.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(dialog).toBeHidden()
  await ui.submitRow(page, code); await ui.approve(page, code)
  await ui.createRule(page, runtime.projectId, 'QL脚本')
  const editor = page.locator('[role="code"].monaco-editor').getByRole('textbox', { name: /Editor content/ })
  await editor.click(); await editor.press('Control+A'); await editor.press('Backspace')
  await page.locator('.se-var-item').filter({ hasText: code }).dblclick()
  await editor.press('End'); await editor.pressSequentially(';')
  const saved = await ui.save(page)
  expect(JSON.parse(saved.revision.modelJson).scriptVarRefs.some(ref => ref.refCode === code && ref.varId)).toBe(true)
  await page.request.post('http://127.0.0.1:18091/reset')
  const first = await ui.execute(page), second = await ui.execute(page)
  expect(first.result).toBe(88); expect(second.result).toBe(88)
  const supplierCalls = (await (await page.request.get('http://127.0.0.1:18091/stats')).json()).count
  expect(supplierCalls).toBeLessThanOrEqual(1)
  expect(first.traceId).toBeTruthy()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '执行日志', exact: true }).click()
  await page.getByPlaceholder('完整 trace_id').fill(first.traceId)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await page.getByRole('row').filter({ hasText: first.traceId }).getByRole('button', { name: '详情', exact: true }).click()
  const detail = page.getByRole('dialog', { name: '日志详情', exact: true })
  await expect(detail).toContainText(first.traceId)
  await expect(detail).toContainText('88')
  await detail.getByRole('tab', { name: /表达式追踪树/ }).click()
  await expect(detail.locator('.trace-wrap').first()).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('source-root-trace.png'), fullPage: true })
  await detail.locator('.el-drawer__close-btn').click()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '外数管理', exact: true }).click()
  await page.getByRole('tab', { name: '调用日志', exact: true }).click()
  await page.getByPlaceholder('模块或规则 trace_id').fill(first.traceId)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  const moduleRow = page.getByRole('row').filter({ hasText: api.apiCode }).first()
  await expect(moduleRow).toBeVisible()
  await moduleRow.getByRole('button', { name: '详情', exact: true }).click()
  const moduleDetail = page.getByRole('dialog', { name: 'API外数调用详情', exact: true })
  await expect(moduleDetail).toContainText(first.traceId)
  await page.screenshot({ path: testInfo.outputPath('source-module-trace.png'), fullPage: true })
  await moduleDetail.locator('.el-drawer__close-btn').click()
  await page.getByPlaceholder('模块或规则 trace_id').fill(second.traceId)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await page.getByRole('row').filter({ hasText: api.apiCode }).first().getByRole('button', { name: '详情', exact: true }).click()
  await expect(moduleDetail).toContainText(second.traceId)
  await expect(moduleDetail).toContainText(/CACHE|HIT/)
  fs.writeFileSync(testInfo.outputPath('source-trace.json'), JSON.stringify({ definitionId: saved.revision.definitionId, traceId: first.traceId, secondTraceId: second.traceId, result: first.result, supplierCalls }))
})
