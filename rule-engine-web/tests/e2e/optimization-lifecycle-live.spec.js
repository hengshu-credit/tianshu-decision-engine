const { test, expect } = require('@playwright/test')
const ui = require('./support/optimizationLive.cjs')
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })

test('真实共用生命周期完成新增驳回、修订发布、撤回更新、停用和删除', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_BASE_URL || !process.env.E2E_ISOLATED_OPTIMIZATION, '仅使用本机隔离环境的全新空项目')
  test.setTimeout(180000)
  const name = `生命周期${Date.now()}`, code = `Lifecycle_${Date.now()}`
  await ui.login(page, '/project')
  const projects = async () => {
    await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '项目管理', exact: true }).click()
    return page.getByRole('row').filter({ hasText: code })
  }
  const openRequest = async () => {
    await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '审批管理', exact: true }).click()
    await page.getByRole('row').filter({ hasText: name }).first().getByRole('button', { name: '查看', exact: true }).click()
  }
  const edit = async (description, disable = false) => {
    await (await projects()).getByRole('button', { name: '编辑', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '编辑项目', exact: true })
    await dialog.getByRole('textbox', { name: '描述', exact: true }).fill(description)
    if (disable) await dialog.locator('.el-switch').click()
    await dialog.getByRole('button', { name: '确定', exact: true }).click()
    await expect(dialog).toBeHidden()
  }
  await page.getByRole('button', { name: '新建项目', exact: true }).click()
  const create = page.getByRole('dialog', { name: '新建项目', exact: true })
  await create.getByRole('textbox', { name: /项目编码$/ }).fill(code)
  await create.getByRole('textbox', { name: /项目名称$/ }).fill(name)
  await create.getByRole('button', { name: '确定', exact: true }).click()
  await expect(create).toBeHidden()
  await ui.submitRow(page, name); await openRequest()
  await page.getByRole('button', { name: '驳回', exact: true }).click()
  const rejection = page.getByRole('dialog', { name: '驳回申请', exact: true })
  await rejection.getByRole('textbox', { name: '驳回原因', exact: true }).fill('请补充业务用途')
  await rejection.getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.locator('.header-meta')).toContainText('已驳回')
  await edit('业务用途已补充')
  await ui.submitRow(page, name); await ui.approve(page, name)
  await expect((await projects()).locator('.governance-resource-status')).toContainText('已发布')
  await edit('撤回后不得生效的说明')
  await ui.submitRow(page, name); await openRequest()
  await page.getByRole('button', { name: '取消申请', exact: true }).click()
  await page.getByRole('dialog', { name: '取消申请', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.locator('.header-meta')).toContainText('已取消')
  await expect(await projects()).toContainText('业务用途已补充')
  await expect(await projects()).not.toContainText('撤回后不得生效')
  await edit('已停用的空项目', true)
  await ui.submitRow(page, name); await ui.approve(page, name)
  await expect((await projects()).locator('.governance-resource-status')).toContainText('已停用')
  await (await projects()).getByRole('button', { name: '删除', exact: true }).click()
  const deleted = page.waitForResponse(response => /\/governance\/resources\/PROJECT\/\d+\/delete$/.test(response.url()) && response.request().method() === 'POST')
  await page.getByRole('dialog', { name: '确认', exact: true }).getByRole('button', { name: '确定', exact: true }).click()
  const deletion = await (await deleted).json()
  expect(deletion.code).toBe('000000')
  expect(deletion.data.approvalRequestId).toBeTruthy()
  await page.goto(`${process.env.E2E_BASE_URL}/#/approval/${deletion.data.approvalRequestId}`)
  await page.getByRole('button', { name: '提交审批', exact: true }).click()
  await page.getByRole('dialog', { name: '提交审批', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await page.getByRole('button', { name: '通过并生效', exact: true }).click()
  await page.getByRole('dialog', { name: '通过并立即生效', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.locator('.header-meta')).toContainText('已通过')
  await expect(await projects()).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('lifecycle-deleted-project.png'), fullPage: true })
})
