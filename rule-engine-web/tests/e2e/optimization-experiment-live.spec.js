const { test, expect } = require('@playwright/test')
const fs = require('node:fs')
const ui = require('./support/optimizationLive.cjs')
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })

test('真实实验 UI 解释比例命中，并用固定旧版本执行空跑组', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_BASE_URL || !process.env.E2E_ISOLATED_OPTIMIZATION || !process.env.E2E_RUNTIME_ENV_FILE, '需要本机已发布的多版本规则')
  test.setTimeout(180000)
  const config = JSON.parse(fs.readFileSync(process.env.E2E_RUNTIME_ENV_FILE, 'utf8'))
  const name = `分流验收${Date.now()}`, code = `Exp_${Date.now()}`
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await ui.login(page, '/experiment')
  await page.getByRole('button', { name: '新建实验', exact: true }).click()
  const project = page.locator('.base-form .el-form-item').first().locator('.el-select')
  await project.click(); await project.locator('input').fill(config.projectCode)
  await page.getByRole('option').filter({ hasText: config.projectCode }).click()
  await page.getByRole('textbox', { name: /实验编码$/ }).fill(code)
  await page.getByRole('textbox', { name: /实验名称$/ }).fill(name)
  await ui.field(page, page.getByPlaceholder('选择要执行的规则').first(), config.ruleCode)
  await page.getByRole('tab', { name: '空跑测试', exact: true }).click()
  const tests = page.getByRole('tabpanel', { name: '空跑测试', exact: true })
  await expect(tests).toContainText('空跑不改写名单')
  await tests.getByText('随机分流', { exact: true }).click()
  await tests.getByRole('button', { name: '添加测试组', exact: true }).click()
  await tests.locator('.ratio-input').getByRole('spinbutton').fill('100')
  await ui.field(page, tests.getByPlaceholder('选择要执行的规则'), config.ruleCode)
  const version = tests.locator('.rule-call-version .el-select')
  await expect(version).toContainText('最新')
  await version.click()
  await page.locator('#' + await version.getByRole('combobox').getAttribute('aria-controls')).getByRole('option', { name: 'v1', exact: true }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByText(/草稿已保存/).first()).toBeVisible()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '分流实验', exact: true }).click()
  await ui.submitRow(page, name); await ui.approve(page, name)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '分流实验', exact: true }).click()
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '验证执行', exact: true }).click()
  const trial = page.getByRole('dialog', { name: '验证执行分流实验', exact: true })
  await expect(trial).toContainText('执行准备状态')
  await trial.getByRole('textbox', { name: '请求唯一键', exact: true }).fill('same-business-case')
  const response = page.waitForResponse(item => item.url().includes('/experiment/execute/') && item.request().method() === 'POST')
  await trial.getByRole('button', { name: '验证执行', exact: true }).click()
  const result = await (await response).json()
  expect(result.code, result.message).toBe('000000')
  expect(result.data.productionGroup.result).toBe(45)
  expect(result.data.productionGroup.ruleVersion).toBeGreaterThan(1)
  expect(result.data.testGroups).toHaveLength(1)
  expect(result.data.testGroups[0].result).toBe(42)
  expect(result.data.testGroups[0].ruleVersion).toBe(1)
  await expect(trial.locator('.execution-production-card')).toContainText('比例分流命中桶位:')
  await expect(trial.locator('.execution-test-group')).toContainText('测试组比例分流命中桶位:')
  await expect(trial.locator('.execution-test-group')).toContainText('v1')
  await page.screenshot({ path: testInfo.outputPath('experiment-group-reasons-and-versions.png'), fullPage: true })
  expect(errors).toEqual([])
})
