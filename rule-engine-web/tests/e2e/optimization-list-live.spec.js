const { test, expect } = require('@playwright/test')
const path = require('node:path')
const base = process.env.E2E_BASE_URL
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })

test('真实名单 UI 导入错误修正、审批生效及重复导入不重复写入', async ({ page }, testInfo) => {
  test.skip(!base || !process.env.E2E_ISOLATED_OPTIMIZATION, '只运行于显式指定的本机隔离环境')
  test.setTimeout(180000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${base}/#/list`)
  await page.locator('input[autocomplete="username"]').fill(process.env.E2E_USERNAME)
  await page.locator('input[autocomplete="current-password"]').fill(process.env.E2E_PASSWORD)
  await page.locator('button[type="submit"]').click()
  await page.getByRole('button', { name: '新建名单库', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建名单库', exact: true })
  const name = `名单验收${Date.now()}`
  await dialog.locator('.el-form-item').filter({ hasText: '作用范围' }).locator('.el-select').click()
  await page.getByRole('option', { name: '全局', exact: true }).click()
  await dialog.getByRole('textbox', { name: /名单编码$/ }).fill(`List_${Date.now()}`)
  await dialog.getByRole('textbox', { name: /名单名称$/ }).fill(name)
  await dialog.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '发布', exact: true }).click()
  await page.getByRole('dialog', { name: '提交发布审批', exact: true }).getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByText('已提交发布审批，生产内容在审批通过前保持原状', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '审批管理', exact: true }).click()
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '查看', exact: true }).click()
  await page.getByRole('button', { name: '通过并生效', exact: true }).click()
  await page.getByRole('dialog', { name: '通过并立即生效', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.locator('.header-meta')).toContainText('已通过', { timeout: 30000 })
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '名单管理', exact: true }).click()
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '详情', exact: true }).click()
  await expect(page).toHaveURL(/#\/list\/\d+/)
  const listUrl = page.url()
  const upload = async filename => {
    const response = page.waitForResponse(item => /\/list\/\d+\/import$/.test(new URL(item.url()).pathname) && item.request().method() === 'POST', { timeout: 20000 })
    await page.locator('input[type="file"]').setInputFiles(path.resolve(__dirname, '../fixtures', filename))
    const result = await (await response).json()
    expect(result.code, result.message).toBe('000000')
    return result.data
  }
  const invalid = await upload('list-invalid.xlsx')
  expect(invalid.submittable).toBe(false); expect(invalid.invalidCount).toBe(1)
  await expect(page.locator('.batch-feedback')).toContainText('第 3 行')
  await expect(page.getByRole('cell', { name: '隔离名单甲', exact: true })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('list-import-invalid.png'), fullPage: true })
  const corrected = await upload('list-corrected.xlsx')
  expect(corrected.submittable).toBe(true); expect(corrected.addCount).toBe(2); expect(corrected.duplicateCount).toBe(1)
  await expect(page).toHaveURL(/#\/approval\/\d+/)
  await page.getByRole('button', { name: '提交审批', exact: true }).click()
  await page.getByRole('dialog', { name: '提交审批', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await page.getByRole('button', { name: '通过并生效', exact: true }).click()
  await page.getByRole('dialog', { name: '通过并立即生效', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.locator('.header-meta')).toContainText('已通过', { timeout: 30000 })
  await page.goto(listUrl)
  await expect(page.getByRole('cell', { name: '隔离名单甲', exact: true })).toHaveCount(1)
  await expect(page.getByRole('cell', { name: '隔离名单乙', exact: true })).toHaveCount(1)
  const duplicate = await upload('list-corrected.xlsx')
  expect(duplicate.submittable).toBe(false); expect(duplicate.duplicateCount).toBe(3); expect(duplicate.invalidCount).toBe(0)
  await expect(page.getByRole('cell', { name: '隔离名单甲', exact: true })).toHaveCount(1)
  await page.getByRole('tab', { name: '变更日志', exact: true }).click()
  await expect(page.getByRole('cell', { name: '隔离名单甲', exact: true })).toHaveCount(1)
  await expect(page.getByRole('cell', { name: '隔离名单乙', exact: true })).toHaveCount(1)
  await page.getByRole('tab', { name: '名单内容', exact: true }).click()
  await page.setViewportSize({ width: 560, height: 1000 })
  await expect(page.getByTestId('record-filter-toolbar').getByRole('button', { name: '导入并审批', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('list-import-duplicate-mobile.png'), fullPage: true })
  expect(errors).toEqual([])
})
