const { test, expect } = require('@playwright/test')

const baseUrl = process.env.E2E_BASE_URL
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })
async function login(page, username, password, path = '/project') {
  await page.goto(`${baseUrl}/#${path}`)
  await page.locator('input[autocomplete="username"]').fill(username)
  await page.locator('input[autocomplete="current-password"]').fill(password)
  await page.locator('button[type="submit"]').click()
  await expect(page.locator('button[type="submit"]')).toBeHidden()
}
async function approveCurrent(page) {
  await page.getByRole('button', { name: '通过并生效', exact: true }).click()
  await page.getByRole('dialog', { name: '通过并立即生效', exact: true }).getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByText('已通过', { exact: true }).first()).toBeVisible({ timeout: 30000 })
}
async function publishDatabase(page, name) {
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '数据库管理', exact: true }).click()
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '发布', exact: true }).click()
  await page.getByRole('dialog', { name: '提交发布审批', exact: true }).getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByText('已提交发布审批，生产内容在审批通过前保持原状', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '审批管理', exact: true }).click()
  await page.getByRole('row').filter({ hasText: name }).first().getByRole('button', { name: '查看', exact: true }).click()
  await expect(page).toHaveURL(/#\/approval\/\d+/)
  await expect(page.locator('.layout-main')).toContainText(name)
  await approveCurrent(page)
}
async function selectTestRule(page, code) {
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '规则测试', exact: true }).click()
  const choice = page.locator('.el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: /^规则$/ }) }).locator('.el-select')
  await choice.click()
  await choice.locator('input').fill(code)
  await page.getByRole('option').filter({ hasText: code }).click()
  await expect(page.getByTestId('rule-test-source')).toContainText(/草稿\s*1/)
}
async function checkRegression(page, assertion) {
  await page.getByRole('button', { name: '回归报告', exact: true }).click()
  const response = page.waitForResponse(item => item.url().endsWith('/reports/check') && item.request().method() === 'POST')
  await page.getByRole('button', { name: '复核当前修订', exact: true }).click()
  const body = await (await response).json()
  expect(body.code).toBe('000000')
  assertion(body.data)
  await page.getByRole('dialog', { name: '回归报告', exact: true }).locator('.el-drawer__close-btn').click()
}
