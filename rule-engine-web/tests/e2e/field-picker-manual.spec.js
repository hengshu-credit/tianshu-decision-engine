const { expect, test } = require('@playwright/test')
const { installDistRoutes } = require('./support/distRoutes.cjs')
const { createDesignerApiData } = require('./support/designerFixtures.cjs')

async function replaceThreshold(content, value) {
  await content.click()
  await content.press('ControlOrMeta+A')
  await content.fill(value)
}

test('阈值自动推荐、用户手选优先；路径、阈值与 fx 面板各自保留草稿', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const { assertClean } = await installDistRoutes(page, { apiData: createDesignerApiData() })
  await page.goto('http://tianshu.local/index.html#/designer/table/101')
  await page.getByRole('button', { name: '添加行', exact: true }).click()
  const field = page.getByPlaceholder('选择左操作数...').first()
  const panel = page.locator('.fp-panel:visible')
  await field.click()
  const search = panel.getByRole('textbox', { name: '搜索字段名称或编码' })
  await search.fill('income')
  await panel.locator('.fp-row').filter({ hasText: '收入' }).click()
  await page.mouse.click(5, 5)
  await expect(panel).toHaveCount(0)
  await expect(field).toHaveValue('')
  await field.click()
  await expect(search).toHaveValue('income')
  await expect(panel.locator('.fp-preview')).toContainText('收入')
  await panel.getByRole('button', { name: '输入阈值', exact: true }).click()
  const content = panel.getByRole('textbox', { name: /^阈值内容/ })
  await expect(panel.locator('.monaco-editor-container')).toBeVisible()
  await replaceThreshold(content, '00123')
  await expect(panel.locator('.operand-type-recommendation')).toContainText('字符串')
  await replaceThreshold(content, '123.5')
  await expect(panel.locator('.operand-type-recommendation')).toContainText('数值')
  await panel.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '阈值数据类型' }) }).click()
  await page.getByRole('option', { name: '字符串 (STRING)', exact: true }).click()
  await replaceThreshold(content, '678')
  await expect(panel.locator('.operand-type-recommendation')).toContainText('按你的选择：字符串')
  await page.mouse.click(5, 5)
  await expect(panel).toHaveCount(0)
  await expect(field).toHaveValue('')
  await field.click()
  await expect(content).toHaveValue('678')
  await expect(panel.locator('.operand-type-recommendation')).toContainText('按你的选择：字符串')
  await panel.getByRole('button', { name: '写入路径', exact: true }).click()
  await page.mouse.move(5, 5)
  const path = panel.getByRole('textbox', { name: '字段路径', exact: true })
  await path.fill('TaxRequest.amount')
  await expect(panel.locator('.operand-path-match')).toContainText('金额')
  await expect(field).toHaveValue('')
  await panel.getByRole('button', { name: '输入阈值', exact: true }).click()
  await expect(content).toHaveValue('678')
  await expect(panel.locator('.operand-type-recommendation')).toContainText('按你的选择：字符串')
  await panel.getByRole('button', { name: 'ƒx 组合表达式', exact: true }).click()
  await expect(panel.locator('.expression-editor--compact')).toBeVisible()
  await panel.getByRole('button', { name: '写入路径', exact: true }).click()
  await expect(path).toHaveValue('TaxRequest.amount')
  await page.mouse.click(5, 5)
  await expect(panel).toHaveCount(0)
  await field.click()
  await expect(path).toHaveValue('TaxRequest.amount')
  await expect(page.locator('.var-picker-popover:visible')).toHaveCSS('opacity', '1')
  await page.screenshot({ path: testInfo.outputPath('path-panel.png'), animations: 'disabled' })
  await panel.getByRole('button', { name: '使用路径', exact: true }).click()
  await expect(field).toHaveValue(/TaxRequest.amount/)
  await field.click()
  await panel.getByRole('button', { name: '输入阈值', exact: true }).click()
  await replaceThreshold(content, '[9007199254740993,2]')
  await expect(panel.locator('.monaco-editor-container .view-lines')).toHaveText('[9007199254740993,2]')
  await expect(panel.locator('.operand-type-recommendation')).toContainText('按你的选择：字符串')
  await panel.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '阈值数据类型' }) }).click()
  await page.getByRole('option', { name: '自动推荐', exact: true }).click()
  await expect(panel.locator('.monaco-editor-container')).toBeVisible()
  await expect(panel.locator('.operand-type-recommendation')).toContainText('列表')
  await expect(panel.locator('.monaco-editor-container .view-lines')).toHaveText('[9007199254740993,2]')
  await panel.getByRole('button', { name: '应用阈值', exact: true }).click()
  await expect(field).toHaveValue('[9007199254740993,2]')
  assertClean()
})

test('Monaco 阈值支持多行草稿、撤销重做，应用时保留大数和 false', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const { assertClean } = await installDistRoutes(page, { apiData: createDesignerApiData() })
  await page.goto('http://tianshu.local/index.html#/designer/table/101')
  await page.getByRole('button', { name: '添加行', exact: true }).click()
  const field = page.getByPlaceholder('选择左操作数...').first()
  const panel = page.locator('.fp-panel:visible')
  await field.click()
  await panel.getByRole('button', { name: '输入阈值', exact: true }).click()
  const content = panel.getByRole('textbox', { name: /^阈值内容/ })
  const lines = panel.locator('.monaco-editor-container .view-lines')
  await replaceThreshold(content, '低风险')
  await content.press('End')
  await content.press('Enter')
  await content.pressSequentially('review')
  await expect(lines.locator('.view-line')).toHaveText(['低风险', 'review'])
  await panel.getByRole('button', { name: '暂存并关闭', exact: true }).click()
  await field.click()
  await expect(lines.locator('.view-line')).toHaveText(['低风险', 'review'])
  await replaceThreshold(content, '9007199254740993')
  await content.press('End')
  await content.pressSequentially('4')
  await expect(lines).toHaveText('90071992547409934')
  await content.press('ControlOrMeta+Z')
  await expect(lines).toHaveText('9007199254740993')
  await content.press('ControlOrMeta+Y')
  await expect(lines).toHaveText('90071992547409934')
  await expect(panel.locator('.operand-type-recommendation')).toContainText('自动推荐：数值')
  await page.screenshot({ path: testInfo.outputPath('monaco-threshold.png'), animations: 'disabled' })
  await panel.getByRole('button', { name: '应用阈值', exact: true }).click()
  await expect(field).toHaveValue('90071992547409934')
  await field.click()
  await replaceThreshold(content, 'false')
  await expect(panel.locator('.operand-type-recommendation')).toContainText('自动推荐：布尔')
  await content.press('ControlOrMeta+Enter')
  await expect(field).toHaveValue('false')
  await expect(panel).toHaveCount(0)
  assertClean()
})
