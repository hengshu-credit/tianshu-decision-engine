const { test, expect } = require('@playwright/test')
const ui = require('./support/optimizationLive.cjs')
test.use({ actionTimeout: 20000, navigationTimeout: 30000 })

test('真实函数 UI 展示签名影响、审批和参数执行，编辑后旧影响报告失效', async ({ page }, testInfo) => {
  test.skip(!process.env.E2E_BASE_URL || !process.env.E2E_ISOLATED_OPTIMIZATION, '仅在本机隔离环境创建函数')
  test.setTimeout(120000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const name = `金额翻倍${Date.now()}`, code = `Double_${Date.now()}`
  await ui.login(page, '/function')
  await page.getByRole('button', { name: '新建函数', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '新建函数', exact: true })
  await dialog.locator('.el-form-item').filter({ hasText: '作用范围' }).locator('.el-select').click()
  await page.getByRole('option', { name: /全局/ }).click()
  await dialog.getByRole('textbox', { name: /函数编码$/ }).fill(code)
  await dialog.getByRole('textbox', { name: /函数名称$/ }).fill(name)
  await dialog.getByRole('textbox', { name: '说明', exact: true }).fill('输入金额（元），返回两倍金额；不接受空值。')
  await dialog.locator('.el-form-item').filter({ hasText: '返回类型' }).locator('.el-select').click()
  await page.getByRole('option', { name: '数值 (NUMBER)', exact: true }).click()
  if (!await dialog.getByRole('textbox', { name: '参数 1 名称', exact: true }).count()) await dialog.getByRole('button', { name: '添加参数', exact: true }).click()
  await dialog.getByRole('textbox', { name: '参数 1 名称', exact: true }).fill('amount')
  await dialog.getByRole('textbox', { name: '参数 1 显示名称', exact: true }).fill('金额')
  const parameterType = dialog.getByRole('combobox', { name: '参数 1 业务类型', exact: true })
  await dialog.locator('.function-parameter-row').first().locator('.el-select').click()
  await page.locator('#' + await parameterType.getAttribute('aria-controls')).getByRole('option', { name: '数值 (NUMBER)', exact: true }).click()
  await dialog.locator('.monaco-editor[role="code"]').click(); await page.keyboard.press('Control+A'); await page.keyboard.insertText('return amount * 2;')
  await dialog.getByRole('button', { name: '检查签名与引用影响', exact: true }).click()
  await expect(dialog.locator('.function-impact')).toContainText(`${code}(amount: NUMBER) → NUMBER`)
  await expect(dialog.locator('.function-impact')).toContainText('需要复核：新建函数')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog).toBeHidden()
  await ui.submitRow(page, name); await ui.approve(page, name)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '函数管理', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: name })
  await row.getByRole('button', { name: '测试', exact: true }).click()
  const trial = page.getByRole('dialog', { name: '函数测试', exact: true })
  const input = trial.getByRole('textbox', { name: /Editor content/ }).first()
  await expect(input).toHaveValue(/amount/)
  await input.click(); await input.press('Control+A'); await input.press('Backspace'); await input.fill('{"amount":21}')
  await expect(input).toHaveValue('{"amount":21}')
  const executed = page.waitForResponse(response => /\/function\/\d+\/test$/.test(response.url()) && response.request().method() === 'POST')
  await trial.getByRole('button', { name: '执行测试', exact: true }).click()
  const result = await (await executed).json()
  expect(result.code, result.message).toBe('000000'); expect(result.data.success).toBe(true); expect(result.data.result).toBe(42)
  await trial.getByRole('button', { name: '关闭', exact: true }).click()
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  const edit = page.getByRole('dialog', { name: '编辑函数', exact: true })
  await edit.getByRole('button', { name: '检查签名与引用影响', exact: true }).click()
  await expect(edit.locator('.function-impact')).toContainText('声明签名与实现内容未改变')
  await edit.getByRole('textbox', { name: '参数 1 名称', exact: true }).fill('changed')
  await expect(edit.locator('.function-impact')).toContainText('配置已变更，请重新检查')
  await edit.getByRole('button', { name: '检查签名与引用影响', exact: true }).click()
  await expect(edit.locator('.function-impact')).toContainText('需要复核：参数名称、顺序或类型')
  await page.screenshot({ path: testInfo.outputPath('function-signature-impact.png'), fullPage: true })
  await edit.getByRole('button', { name: '取消', exact: true }).click()
  expect(errors).toEqual([])
})
